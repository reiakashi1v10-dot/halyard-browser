const DICTS: Record<Lang, Dict> = { en, 'pt-BR': pt, es }
const LOCALES: Record<Lang, string> = { en: 'en-US', 'pt-BR': 'pt-BR', es: 'es-ES' }

let current: Lang = 'en'

export function isLang(v: unknown): v is Lang {
  return v === 'en' || v === 'pt-BR' || v === 'es'
}

export function setLang(lang: Lang | undefined): void {
  current = isLang(lang) ? lang : 'en'
}

export function getLang(): Lang {
  return current
}

/** BCP 47 locale for dates and numbers. */
export function locale(): string {
  return LOCALES[current]
}

export function t(key: I18nKey, vars?: Record<string, string | number>): string {
  let text = DICTS[current][key] ?? en[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v))
  return text
}

/** Names the default spaces get in each language, used to rename them when the language changes. */
export function defaultSpaceNames(id: 'pessoal' | 'trabalho'): string[] {
  const key: I18nKey = id === 'pessoal' ? 'space.personal' : 'space.work'
  return Object.values(DICTS).map((d) => d[key])
}

export function translateIn(lang: Lang, key: I18nKey): string {
  return DICTS[lang][key]
}
